"""Stage A3 audit -- dataset mapping (class * source * split + leakage scan).

Required by `multiguard_non_image_pipeline_fix_plan.md` section 4
"Dataset mapping and balance".
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import pandas as pd

CLASS_NAMES = {
    0: "Real (NewsCLIPpings matched)",
    1: "OOC (NewsCLIPpings mismatched)",
    2: "Manipulated (DGM4 + MMFakeBench tampered)",
    3: "AI-Text (MMFakeBench textual fakes)",
    4: "Fully Fabricated (GenImage MidJourney + DGM4 multi-fake)",
}


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--manifest", type=Path,
                   default=Path("data/processed/forensic_5class_unified_blip2.csv"))
    p.add_argument("--out", type=Path, default=Path("docs/DATASET_MAPPING_AUDIT.md"))
    args = p.parse_args()

    df = pd.read_csv(args.manifest)
    print(f"[A3] manifest: {len(df)} rows, cols={list(df.columns)}")

    L = ["# Dataset mapping audit (Stage A3)", "",
         "> Generated by `phases/v4/scripts/audit_dataset_mapping.py`",
         f"> Manifest: `{args.manifest}` ({len(df)} rows)", ""]

    L.append("## Split totals")
    L.append("")
    L.append("| Split | Rows |")
    L.append("|---|---|")
    split_counts = df["split"].value_counts().to_dict()
    for s in ("train", "val", "test"):
        L.append(f"| {s} | {split_counts.get(s, 0)} |")
    L.append(f"| **Total** | **{len(df)}** |")
    L.append("")

    L.append("## Class * Split (row counts)")
    L.append("")
    L.append("| Class | Train | Val | Test | Total |")
    L.append("|---|---|---|---|---|")
    for cls in range(5):
        cdf = df[df["label"] == cls]
        t = (cdf["split"] == "train").sum()
        v = (cdf["split"] == "val").sum()
        te = (cdf["split"] == "test").sum()
        L.append(f"| {cls} {CLASS_NAMES[cls]} | {t} | {v} | {te} | {len(cdf)} |")
    L.append("")

    L.append("## Class * Source breakdown")
    L.append("")
    L.append("| Class | Source | Train | Val | Test | Total |")
    L.append("|---|---|---|---|---|---|")
    for cls in range(5):
        cdf = df[df["label"] == cls]
        for src in sorted(cdf["source"].unique()):
            sdf = cdf[cdf["source"] == src]
            t = (sdf["split"] == "train").sum()
            v = (sdf["split"] == "val").sum()
            te = (sdf["split"] == "test").sum()
            L.append(f"| {cls} | {src} | {t} | {v} | {te} | {len(sdf)} |")
    L.append("")

    L.append("## Class balance check")
    L.append("")
    L.append("V3.1 spec section 2.b: undersample all classes to the smallest class.")
    L.append("")
    class_totals = df["label"].value_counts().sort_index().to_dict()
    smallest = min(class_totals.values())
    L.append("| Class | Total | Deviation from smallest |")
    L.append("|---|---|---|")
    for cls in range(5):
        n = class_totals[cls]
        dev = n - smallest
        L.append(f"| {cls} | {n} | {'+' if dev > 0 else ''}{dev} |")
    L.append("")
    if max(class_totals.values()) - smallest <= 5:
        L.append("**Verdict:** classes are balanced (within 5 of smallest).")
    else:
        L.append(f"**Verdict:** classes are IMBALANCED (max-min spread = {max(class_totals.values()) - smallest}).")
    L.append("")

    L.append("## Per-split class balance (stratification check)")
    L.append("")
    L.append("V3.1 spec calls for stratified per-class 70/15/15 split.")
    L.append("")
    L.append("| Class | Train | Val | Test | Train% | Val% | Test% |")
    L.append("|---|---|---|---|---|---|---|")
    for cls in range(5):
        cdf = df[df["label"] == cls]
        total = len(cdf)
        t = (cdf["split"] == "train").sum()
        v = (cdf["split"] == "val").sum()
        te = (cdf["split"] == "test").sum()
        L.append(f"| {cls} | {t} | {v} | {te} | {t/total*100:.1f}% | {v/total*100:.1f}% | {te/total*100:.1f}% |")
    L.append("")

    L.append("## Duplicate scan: sample_id appearing in multiple splits")
    L.append("")
    sid_split_count = df.groupby("sample_id")["split"].nunique()
    dup_sids = sid_split_count[sid_split_count > 1]
    if len(dup_sids) == 0:
        L.append("**PASS** -- no `sample_id` appears in more than one split.")
    else:
        L.append(f"**FAIL** -- {len(dup_sids)} `sample_id`s appear in multiple splits.")
        for sid in dup_sids.index[:10]:
            splits_for_sid = df[df["sample_id"] == sid]["split"].unique().tolist()
            L.append(f"  - `{sid}` in splits {splits_for_sid}")
        if len(dup_sids) > 10:
            L.append(f"  - ... and {len(dup_sids) - 10} more")
    L.append("")

    L.append("## Duplicate scan: image_path appearing under multiple labels")
    L.append("")
    path_label = df.groupby("image_path")["label"].nunique()
    conflict_paths = path_label[path_label > 1]
    if len(conflict_paths) == 0:
        L.append("**PASS** -- no `image_path` appears under more than one label.")
    else:
        L.append(f"**FAIL** -- {len(conflict_paths)} `image_path`s appear under multiple labels (label conflicts).")
        for p in conflict_paths.index[:10]:
            labels_for_p = df[df["image_path"] == p]["label"].unique().tolist()
            L.append(f"  - `{p}` -> labels {labels_for_p}")
    L.append("")

    L.append("## Duplicate scan: image_path appearing across train/test")
    L.append("")
    train_paths = set(df[df["split"] == "train"]["image_path"])
    test_paths = set(df[df["split"] == "test"]["image_path"])
    leak_paths = train_paths & test_paths
    if len(leak_paths) == 0:
        L.append("**PASS** -- no `image_path` appears in both train and test splits.")
    else:
        L.append(f"**FAIL** -- {len(leak_paths)} `image_path`s leak from train into test.")
        for p in list(leak_paths)[:10]:
            L.append(f"  - `{p}`")
    L.append("")

    L.append("## Text-image hash duplicates (potential paraphrased leakage)")
    L.append("")
    df["_textimg_hash"] = (df["image_path"].astype(str) + "||" + df["text"].astype(str)).apply(
        lambda x: hashlib.md5(x.encode()).hexdigest()[:16]
    )
    hash_counts = df["_textimg_hash"].value_counts()
    duplicate_pairs = hash_counts[hash_counts > 1]
    if len(duplicate_pairs) == 0:
        L.append("**PASS** -- no (image_path, text) pair appears more than once.")
    else:
        L.append(f"Found {len(duplicate_pairs)} (image_path, text) pairs appearing more than once.")
        L.append("(May be acceptable if intentional across class labels, but should be investigated.)")
    L.append("")

    L.append("## Verdict")
    L.append("")
    failures = 0
    if len(dup_sids) > 0:
        failures += 1
        L.append(f"- Cross-split sample_id leakage: {len(dup_sids)} (FAIL)")
    if len(conflict_paths) > 0:
        failures += 1
        L.append(f"- Conflicting label-per-image: {len(conflict_paths)} (FAIL)")
    if len(leak_paths) > 0:
        failures += 1
        L.append(f"- Train/test image leakage: {len(leak_paths)} (FAIL)")
    if failures == 0:
        L.append("**PASS** -- no split leakage detected. Class mapping matches V3.1 5-class taxonomy.")
    else:
        L.append(f"**{failures} integrity issues found.**")
    L.append("")

    L.append("## Provenance")
    L.append("")
    L.append(f"- Manifest hash (sha256): `{hashlib.sha256(args.manifest.read_bytes()).hexdigest()}`")
    L.append(f"- Manifest path: `{args.manifest}`")

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(L), encoding="utf-8")
    print(f"\n[A3] wrote {args.out}")
    print(f"  duplicates: sid={len(dup_sids)}, label-conflict={len(conflict_paths)}, train/test-leak={len(leak_paths)}")
    return {"sid_dupes": len(dup_sids), "label_conflicts": len(conflict_paths),
            "train_test_leak": len(leak_paths)}


if __name__ == "__main__":
    print(json.dumps(main(), indent=2))
